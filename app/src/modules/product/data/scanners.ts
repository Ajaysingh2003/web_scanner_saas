export function getScannerBySlug(slug: string): ScannerItem | undefined {
  if (!slug) return undefined;
  const normalized = decodeURIComponent(slug).toLowerCase().trim();
  const normalizedDashes = normalized.replace(/_/g, "-");

  return SCANNERS_DATA.find((s) => {
    const sId = s.id.toLowerCase();
    const sTitle = s.title.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    return (
      sId === normalized ||
      sId === normalizedDashes ||
      sTitle === normalizedDashes ||
      sTitle.includes(normalizedDashes) ||
      normalizedDashes.includes(sId)
    );
  });
}

export function getAllScannerSlugs(): string[] {
  return SCANNERS_DATA.map((s) => s.id);
}
